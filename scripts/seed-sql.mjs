// Turns the sample responses in src/mock/api into supabase/seed.sql (run: node scripts/seed-sql.mjs).
// Supabase applies seed.sql after the migrations on `supabase db reset`.
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../src/mock/api/${f}.json`, import.meta.url), "utf8"));
const pick = (o, keys) => Object.fromEntries(keys.map((k) => [k, o[k]]));
const values = Object.values;
// Only the columns present in the data are listed, so every other column keeps its default.
const insert = (table, rows) => {
  const cols = Object.keys(rows[0]).map((c) => `"${c}"`).join(", ");
  return `insert into ${table} (${cols}) select ${cols} from jsonb_populate_recordset(null::${table}, $j$${JSON.stringify(rows)}$j$::jsonb);\n`;
};

const postDetails = values(read("post-details")).map((d) => d.data);
const authors = [...new Map(postDetails.map((p) => [p.author.id, p.author])).values()];
const posts = postDetails.map((p) => pick(p, ["id", "slug", "title", "excerpt", "category", "status", "reading_minutes", "image_url", "published_at", "updated_at", "author_id", "views", "body"]));
const projects = values(read("project-details")).map((d) => pick(d.data, ["id", "slug", "title", "client", "tags", "status", "is_signature", "sort_order", "image_url", "summary", "live_url", "preview_url", "body", "created_at", "published_at"]));
const profile = read("profile").data;
const socials = profile.socials.map((s) => ({ ...s, profile_id: profile.id }));

let sql = "-- Generated by scripts/seed-sql.mjs from src/mock/api. Sample content; replace it in the admin.\n";
sql += insert("authors", authors);
sql += insert("posts", posts);
sql += insert("projects", projects);
sql += insert("profile", [pick(profile, ["id", "display_name", "role", "location", "headline", "status_note", "years_experience", "image_url", "bio"])]);
sql += insert("socials", socials);
sql += insert("skills", read("skills").data);
sql += insert("tools", read("tools").data);
sql += insert("career", read("career").data);
sql += insert("testimonials", read("testimonials").data);
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`seed.sql: ${posts.length} posts, ${projects.length} projects, ${socials.length} socials`);
